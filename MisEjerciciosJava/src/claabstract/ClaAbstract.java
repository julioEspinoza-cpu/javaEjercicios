/*
 * Clase abstracta:
 * - Es una clase que no se puede instanciar directamente.
 * - Se usa como base para otras clases.
 * - Puede tener métodos abstractos, que deben ser implementados por las clases
 * hijas.
 * - Se declara con la palabra reservada abstract.
 * - Se usa para definir una estructura común para varias clases.
 *//*
    * Una clase abstracta es una clase que funciona como plantilla.
    * No se puede crear un objeto de ese tipo directamente.
    * Se utiliza cuando varias clases tienen algo en común,
    * pero cada una debe implementar cierta parte de forma distinta.
    * Se declara con abstract y puede contener métodos abstractos,
    * los cuales obligan a las clases hijas a definir su comportamiento.
    */